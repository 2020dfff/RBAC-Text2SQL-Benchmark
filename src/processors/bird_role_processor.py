"""
Bird-specific role processor for generating database roles using detailed schema files.

This module provides functionality to process Bird dataset databases which use
detailed schema files instead of schema.sql files used by Spider dataset.
"""

import logging
from pathlib import Path
from typing import Optional, List, Dict
from datetime import datetime

from src.role_parser import ParallelRoleGenerator
from src.processors.bird_describer import BirdDatabaseDescriber

logger = logging.getLogger('bird_role_assignment')


class BirdRoleProcessor:
    """
    Bird-specific role processor that works with detailed schema files
    instead of schema.sql files used by Spider dataset.
    
    This processor:
    1. Reads detailed schema files generated by BirdDatabaseDescriber
    2. Creates temporary schema.sql files for compatibility with ParallelRoleGenerator
    3. Processes databases in batches using parallel LLM API calls
    4. Cleans up temporary files after processing
    """
    
    def __init__(self, generator: ParallelRoleGenerator, describer: BirdDatabaseDescriber):
        """
        Initialize the Bird role processor.
        
        Args:
            generator: ParallelRoleGenerator instance for role generation
            describer: BirdDatabaseDescriber instance for schema processing
        """
        self.generator = generator
        self.describer = describer
        
    def read_detailed_schema_file(self, db_path: Path) -> Optional[str]:
        """
        Read detailed schema file for Bird database.
        
        Args:
            db_path: Path to the database directory
            
        Returns:
            str: Schema content without header comments, or None if file not found
        """
        db_name = db_path.name
        schema_file = db_path / f"{db_name}_schema_detailed.txt"
        
        if not schema_file.exists():
            logger.warning(f"Detailed schema file not found for {db_name}: {schema_file}")
            return None
        
        try:
            with open(schema_file, 'r', encoding='utf-8') as f:
                schema_content = f.read()
            
            # Extract the actual schema description (skip the header comments)
            schema_lines = schema_content.split('\n')
            schema_desc = []
            for line in schema_lines:
                if not line.startswith('#') and line.strip():
                    schema_desc.append(line)
            
            return '\n'.join(schema_desc)
            
        except Exception as e:
            logger.error(f"Error reading detailed schema file for {db_name}: {str(e)}")
            return None
    
    def validate_database_files(self, db_paths: List[Path]) -> tuple[List[Path], Dict[str, str], List[str]]:
        """
        Validate and filter databases that have required files.
        
        Args:
            db_paths: List of database directory paths
            
        Returns:
            tuple: (valid_db_paths, sqlite_paths_dict, schema_contents_list)
        """
        valid_dbs = []
        sqlite_paths = {}
        schema_contents = []
        
        for db_path in db_paths:
            db_name = db_path.name
            sqlite_file = db_path / f"{db_name}.sqlite"
            
            if not sqlite_file.exists():
                logger.warning(f"SQLite file not found for {db_name}")
                continue
                
            # Read detailed schema content
            schema_content = self.read_detailed_schema_file(db_path)
            if not schema_content:
                logger.warning(f"Failed to read schema for {db_name}")
                continue
            
            valid_dbs.append(db_path)
            sqlite_paths[db_name] = str(sqlite_file)
            schema_contents.append(schema_content)
        
        return valid_dbs, sqlite_paths, schema_contents
    
    def process_batch_with_temporary_files(self, batch_dbs: List[Path], 
                                         batch_schema_contents: List[str],
                                         batch_sqlite_paths: Dict[str, str]) -> List[Dict]:
        """
        Process a batch of databases by creating temporary schema.sql files.
        
        Args:
            batch_dbs: List of database paths in this batch
            batch_schema_contents: List of schema contents for each database
            batch_sqlite_paths: Dictionary mapping database names to SQLite paths
            
        Returns:
            List[Dict]: Results from parallel processing
        """
        # Create temporary schema.sql files for compatibility with existing ParallelRoleGenerator
        temp_schema_files = []
        
        try:
            for db_path, schema_content in zip(batch_dbs, batch_schema_contents):
                temp_schema_file = db_path / 'schema.sql'
                temp_schema_files.append(temp_schema_file)
                
                # Write schema content to temporary schema.sql file
                with open(temp_schema_file, 'w', encoding='utf-8') as f:
                    f.write(schema_content)
            
            # Process batch using existing parallel logic
            batch_results = self.generator.process_databases_parallel(
                batch_dbs, 
                sqlite_paths=batch_sqlite_paths
            )
            
            return batch_results
            
        finally:
            # Clean up temporary files
            for temp_file in temp_schema_files:
                if temp_file.exists():
                    try:
                        temp_file.unlink()
                    except Exception as e:
                        logger.warning(f"Failed to delete temporary file {temp_file}: {str(e)}")
    
    def process_bird_databases_batch(self, db_paths: List[Path], 
                                   batch_size: int = 8,
                                   run_timestamp: str = None) -> Dict:
        """
        Process multiple Bird databases in batches using parallel processing.
        
        Args:
            db_paths: List of database directory paths to process
            batch_size: Number of databases to process in each batch
            run_timestamp: Timestamp for this processing run
            
        Returns:
            Dict: Processing results with assignments and metadata
        """
        if run_timestamp is None:
            run_timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
        
        # Validate databases and get valid ones
        valid_dbs, sqlite_paths, schema_contents = self.validate_database_files(db_paths)
        
        if not valid_dbs:
            logger.error("No valid databases found for processing")
            return {
                'assignments': {},
                'metadata': {
                    'timestamp': run_timestamp,
                    'total_databases': len(db_paths),
                    'processed_databases': 0,
                    'total_roles_generated': 0,
                    'batch_size': batch_size,
                    'dataset_type': 'bird_dev'
                }
            }
        
        logger.info(f"Found {len(valid_dbs)} valid Bird databases for processing")
        logger.info(f"Valid databases: {[db.name for db in valid_dbs]}")
        
        # Process databases in batches
        all_results = {}
        total_processed = 0
        total_roles = 0
        total_dbs = len(valid_dbs)
        n_batches = (total_dbs + batch_size - 1) // batch_size
        
        for batch_idx in range(n_batches):
            batch_start = batch_idx * batch_size
            batch_end = min(batch_start + batch_size, total_dbs)
            
            batch_dbs = valid_dbs[batch_start:batch_end]
            batch_schema_contents = schema_contents[batch_start:batch_end]
            batch_sqlite_paths = {db.name: sqlite_paths[db.name] for db in batch_dbs}
            
            logger.info(f"\nProcessing Bird Batch {batch_idx + 1}/{n_batches}")
            logger.info(f"Databases: {[db.name for db in batch_dbs]}")
            
            # Process this batch
            try:
                batch_results = self.process_batch_with_temporary_files(
                    batch_dbs, batch_schema_contents, batch_sqlite_paths
                )
                
                # Process batch results
                batch_processed = 0
                batch_roles = 0
                
                for result in batch_results:
                    if result and result.get('roles'):
                        batch_processed += 1
                        roles_count = len(result['roles'])
                        batch_roles += roles_count
                        all_results[result['database']] = result['roles']
                        
                        logger.info(f"  ✓ {result['database']}: {roles_count} roles generated")
                    else:
                        logger.warning(f"  ✗ No roles generated for database in batch {batch_idx + 1}")
                
                total_processed += batch_processed
                total_roles += batch_roles
                
                logger.info(f"Batch {batch_idx + 1} completed: {batch_processed}/{len(batch_dbs)} databases, {batch_roles} roles")
                
            except Exception as e:
                logger.error(f"Error processing batch {batch_idx + 1}: {str(e)}")
                continue
        
        return {
            'assignments': all_results,
            'metadata': {
                'timestamp': run_timestamp,
                'total_databases': len(db_paths),
                'processed_databases': total_processed,
                'total_roles_generated': total_roles,
                'batch_size': batch_size,
                'dataset_type': 'bird_dev'
            }
        }
    
    def save_role_assignments(self, assignments_data: Dict, output_dir: Path, 
                            filename_suffix: str = None) -> Path:
        """
        Save role assignments to JSON file.
        
        Args:
            assignments_data: Dictionary containing assignments and metadata
            output_dir: Directory to save the output file
            filename_suffix: Optional suffix for the filename
            
        Returns:
            Path: Path to the saved file
        """
        if filename_suffix is None:
            filename_suffix = assignments_data['metadata']['timestamp']
        
        output_file = output_dir / f"role_assignments_bird_dev_{filename_suffix}.json"
        
        with open(output_file, 'w', encoding='utf-8') as f:
            import json
            json.dump(assignments_data, f, ensure_ascii=False, indent=2)
        
        logger.info(f"Bird role assignments saved to: {output_file}")
        logger.info(f"File size: {output_file.stat().st_size:,} bytes")
        
        return output_file